class TestSearchNoResults:
    """AC5: no matches shows an explicit empty-result message, no items."""

    def test_unmatched_keyword_shows_empty_message_and_no_items(
        self, page: Page, monkeypatch
    ) -> None:
        _load_with_index(page, monkeypatch, SEARCH_INDEX)

        page.fill("#search-input", "nonexistent-keyword-xyz")

        assert page.locator("#search-results li").count() == 0
        empty_message = page.locator("#search-empty")
        assert empty_message.is_visible()
        assert "查無" in empty_message.text_content()


class TestSearchResultsNotPaginated:
    """AC6: more than 10 matches still render all on one page, no pagination."""

    def test_more_than_ten_matches_all_render_without_pagination_controls(
        self, page: Page, monkeypatch
    ) -> None:
        many_items = [
            {
                "id": f"a{i}",
                "title": f"Common headline number {i}",
                "content": "filler",
                "published_at": "2026-01-01T00:00:00",
            }
            for i in range(15)
        ]
        _load_with_index(page, monkeypatch, many_items)

        page.fill("#search-input", "Common headline")

        assert page.locator("#search-results li").count() == 15
        # No pagination control / "load more" affordance anywhere on the page.
        assert page.get_by_text("下一頁").count() == 0
        assert page.get_by_text("顯示更多").count() == 0
        assert page.locator("[class*='pagination']").count() == 0


class TestSearchEmptyInputShowsNothing:
    """AC7: on load, before any input, no results and no empty-state message."""

    def test_freshly_loaded_page_shows_no_results_and_no_empty_message(
        self, page: Page, monkeypatch
    ) -> None:
        _load_with_index(page, monkeypatch, SEARCH_INDEX)

        assert page.locator("#search-results li").count() == 0
        assert not page.locator("#search-empty").is_visible()

    def test_clearing_input_after_a_search_also_shows_no_empty_message(
        self, page: Page, monkeypatch
    ) -> None:
        """Guards the same AC7 behaviour is preserved when the user backs out
        a query entirely rather than just never having typed anything."""
        _load_with_index(page, monkeypatch, SEARCH_INDEX)

        page.fill("#search-input", "nonexistent-keyword-xyz")
        assert page.locator("#search-empty").is_visible()

        page.fill("#search-input", "")

        assert page.locator("#search-results li").count() == 0
        assert not page.locator("#search-empty").is_visible()


class TestSearchIsClientSideOnly:
    """AC8: matching happens purely client-side; no backend /articles* calls."""

    def test_searching_never_requests_backend_articles_api(
        self, page: Page, monkeypatch
    ) -> None:
        requested_urls = _load_with_index(page, monkeypatch, SEARCH_INDEX)

        for query in ["Sunrise", "keyword", "hiking", "nonexistent-keyword-xyz", ""]:
            page.fill("#search-input", query)

        assert not any("/articles" in url for url in requested_urls)
        # The only network fetch made is the pre-downloaded search index.
        assert any("/search/index.json" in url for url in requested_urls)
